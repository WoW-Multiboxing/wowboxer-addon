#!/usr/bin/env node
/* Generates WoWBoxer/Data/<Game>/*.lua per game (docs/multi-flavor-plan.md §0: data per game, engine shared).
   Forever: from the frozen companion seed (vendor/companion/app_data.json).
   Classic Era: the same seed until the Era data pipeline (plan step 3); in game its macros are filtered by the live
   spellbook. Each file loads on every client and returns at once unless ns.dataGame (Game.lua) is its game.
   Same data as the web companion; only what the addon needs (no rank tooltips, no research notes).
   Cast/cooldown/duration seconds are computed with the companion's own engine (E.castSec, E.cdSec, E.durSec),
   so the Lua engine never re-parses tooltip strings.
   Usage: node tools/build_data.js            (writes WoWBoxer/Data/<Game>/)
          node tools/build_data.js --check    (fails if the committed files are stale) */
'use strict';
const fs = require('fs');
const path = require('path');
const { load } = require('./companion');

const DATA = path.join(__dirname, '..', 'WoWBoxer', 'Data');
// game key (ns.dataGame) -> folder, and where its data comes from
const GAMES = [
  { key: 'forever', dir: 'Forever', title: 'WoW Forever', from: 'the WoW Forever Multibox Companion data (vendor/companion, frozen seed)' },
  { key: 'era', dir: 'Era', title: 'Classic Era', client: 'era', build: '1.15.9.70576' },
  { key: 'tbc', dir: 'TBC', title: 'TBC Anniversary', client: 'tbc', build: '2.5.6.70577' },
];
const { D, E, K } = load();

const KEYWORDS = new Set('and break do else elseif end false for function if in local nil not or repeat return then true until while goto'.split(' '));
function luaStr(s) {
  return '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\r/g, '\\r')
    .replace(/[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]/g, c => '\\' + c.charCodeAt(0)) + '"';
}
function toLua(v, ind) {
  ind = ind || '';
  if (v === null || v === undefined) return 'nil';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') { if (!isFinite(v)) throw new Error('non-finite number'); return String(v); }
  if (typeof v === 'string') return luaStr(v);
  if (Array.isArray(v)) {
    if (!v.length) return '{}';
    const simple = v.every(x => x === null || typeof x !== 'object');
    if (simple) return '{' + v.map(x => toLua(x)).join(',') + '}';
    return '{\n' + v.map(x => ind + ' ' + toLua(x, ind + ' ')).join(',\n') + '\n' + ind + '}';
  }
  const keys = Object.keys(v).filter(k => v[k] !== undefined && v[k] !== null);
  if (!keys.length) return '{}';
  const parts = keys.map(k => ((/^[A-Za-z_][A-Za-z0-9_]*$/.test(k) && !KEYWORDS.has(k)) ? k : '[' + luaStr(k) + ']') + '=' + toLua(v[k], ind + ' '));
  const flat = '{' + parts.join(',') + '}';
  if (flat.length < 160 && !flat.includes('\n')) return flat;
  return '{\n' + parts.map(p => ind + ' ' + p).join(',\n') + '\n' + ind + '}';
}

const round3 = x => Math.round(x * 1000) / 1000;
function timing(s) { return { castFirst: round3(E.castSec(s, 'first')), castLast: round3(E.castSec(s, 'last')), cdSec: round3(E.cdSec(s)), durSec: round3(E.durSec(s)) }; }

function spellOut(s) {
  return Object.assign({
    id: s.id, name: s.name, category: s.category, action: s.action, icon: s.icon, level: s.level, gate: s.gate,
    talent: s.talent, form: s.form, race: s.race, lock: s.lock, school: s.school, disputed: s.disputed ? true : undefined,
    gateNote: s.gateNote, forever: s.forever,
    ranks: (s.ranks || []).map(r => ({ r: r.r, l: r.l, id: r.id })),
  }, timing(s));
}
function guideOut(g) {
  const src = g.source || {};
  return { id: g.id, spec: g.spec, label: g.label, kind: g.kind, default: !!g.default, note: g.note || undefined,
    priorities: g.priorities || undefined,
    source: { site: src.site, author: src.author, title: src.title, url: src.url, updated: src.updated, scope: src.scope, purpose: src.purpose },
    order: g.order };
}

const header = g => '-- GENERATED by tools/build_data.js for ' + g.title + ' from ' + g.from + '. Do not edit.\n' +
  '-- Talent data: Zephras (zephras.com, CC BY 4.0, changed) + The Forever Era; spells: The Forever Era / wowforevertalents.\n' +
  '-- World of Warcraft names and icons (c) Blizzard Entertainment.\n';
// every data file loads on every client and stops here unless it is the running game's (Game.lua sets ns.dataGame)
const guard = g => 'local _, ns = ...\nif ns.dataGame ~= ' + luaStr(g.key) + ' then return end\n';

function filesFor(g) {
  const files = {};
  // ---- common
  const racials = {};
  for (const [k, r] of Object.entries(D.racials)) {
    racials[k] = { name: r.name, faction: r.faction, racials: r.racials.map(x => {
      // the same object the companion builds in racialsOf(), for the timing numbers
      const obj = { name: x.name, ranks: [{ r: 1, cd: x.cd, cast: x.cast, tx: x.tx, id: x.spellId }] };
      return Object.assign({ id: x.id, name: x.name, passive: !!x.passive, icon: x.icon, spellId: x.spellId, forever: x.forever, only: x.only, note: x.note }, timing(obj));
    }) };
  }
  const common = {
    meta: { companion: D.meta.version, built: D.meta.built, talentBuild: D.meta.talentBuild, spellBuild: D.meta.spellBuild, overrides: D.meta.overrides },
    classOrder: D.classOrder, classes: D.classes, races: D.races, racials, core: D.core,
    engage: Object.assign({ id: K.ENGAGE.id, name: K.ENGAGE.name, level: K.ENGAGE.level, category: K.ENGAGE.category, action: K.ENGAGE.action, icon: K.ENGAGE.icon, gate: K.ENGAGE.gate, ranks: [] }, timing(K.ENGAGE)),
    roleSpec: K.ROLE_SPEC,
    reviewedNotIncluded: D.reviewedNotIncluded.map(x => ({ cls: x.cls, title: x.title, reason: x.reason })),
  };
  files['Common.lua'] = header(g) + guard(g) + 'local D = ns.Data\n' +
    Object.entries(common).map(([k, v]) => 'D.' + k + ' = ' + toLua(v) + '\n').join('') +
    'D.talents, D.spells, D.guides = {}, {}, {}\n';

  for (const cls of D.classOrder) {
    const T = D.talents[cls];
    const talents = { trees: T.trees.map(t => ({ n: t.n, f: t.f, i: t.i })), nodes: T.nodes.map(n => ({ k: n.k, n: n.n, t: n.t, r: n.r, c: n.c, m: n.m, i: n.i, f: n.f })), arrows: T.arrows };
    const spells = D.spells.filter(s => s.cls === cls).map(spellOut);
    const guides = D.guides.filter(g => g.cls === cls).map(guideOut);
    const name = 'Class_' + cls + '.lua';
    files[name] = header(g) + guard(g) + 'local D = ns.Data\n' +
      'D.talents.' + cls + ' = ' + toLua(talents) + '\n' +
      'D.spells.' + cls + ' = ' + toLua(spells) + '\n' +
      'D.guides.' + cls + ' = ' + toLua(guides) + '\n';
  }

  // ---- Wowhead talent-calculator order (vendor/wowhead, read-only): names + max ranks per tree, for the link import
  const WH = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'vendor', 'wowhead', 'forever-trees.json'), 'utf8'));
  const whOut = { hashVersion: WH.hashVersion, tokens: WH.tokens, trees: {} };
  for (const cls of D.classOrder) if (WH[cls]) whOut.trees[cls] = WH[cls].map(tree => tree.map(w => ({ n: w.n, m: w.m })));
  files['WowheadOrder.lua'] = '-- GENERATED by tools/build_data.js for ' + g.title + ' from vendor/wowhead/forever-trees.json (Wowhead WoW Forever talent calculator,\n' +
    '-- hash ' + WH.hashVersion + '). Only the order of the talents is used, to read talent links. Names (c) Blizzard. Do not edit.\n' +
    guard(g) + 'ns.Data.wowhead = ' + toLua(whOut) + '\n';
  return files;
}

// ---- games with their own client data (Classic Era, TBC Anniversary): talent trees, class spell ranks, trainer
// levels and icons from the client's own tables (datasrc/<game>/blizzard-<build>.json, tools/fetch_client.py); macro
// rules per spell from the seed where the name matches, else from datasrc/<game>/spells.json (renames + new spells);
// the recommended macros per class and role (core) from spells.json; races from races.json.
// Talent guides: WoWBoxer's starter build per class and role (datasrc/<game>/guides.json, ranks per talent), turned
// into a point order here: the main tree first, rows first; every point must be legal (names, rows, prerequisites)
// and the build must use every point of the game, else the build stops with an error.
function starterOrder(Tg, nodeByName, ranks, maxPoints, where, problems) {
  const want = [];
  const perTree = [0, 0, 0];
  for (const [name, n] of Object.entries(ranks)) {
    const node = nodeByName[name];
    if (!node) { problems.push(where + ': unknown talent ' + name); continue; }
    if (n > node.m) problems.push(where + ': ' + name + ' has ' + n + ' ranks, max ' + node.m);
    want.push({ node, n }); perTree[node.t] += n;
  }
  const main = perTree.indexOf(Math.max(...perTree));
  want.sort((a, b) => ((a.node.t !== main) - (b.node.t !== main)) || a.node.r - b.node.r || a.node.t - b.node.t || a.node.c - b.node.c);
  const rest = [];
  for (const w of want) for (let i = 0; i < w.n; i++) rest.push(w.node.k);
  const order = [], counts = {};
  while (rest.length) {
    const i = rest.findIndex(k => !E.addBlocker(Tg, counts, k, maxPoints));
    if (i < 0) { problems.push(where + ': cannot place ' + rest[0] + ' (' + E.addBlocker(Tg, counts, rest[0], maxPoints).text + ')'); break; }
    const k = rest.splice(i, 1)[0];
    order.push(k); counts[k] = (counts[k] || 0) + 1;
  }
  if (order.length !== maxPoints) problems.push(where + ': ' + order.length + ' points, the game has ' + maxPoints);
  return { order, main, split: perTree.join('/') };
}
function filesForClient(g) {
  const SRC = path.join(__dirname, '..', 'datasrc', g.client);
  const BZ = JSON.parse(fs.readFileSync(path.join(SRC, 'blizzard-' + g.build + '.json'), 'utf8'));
  const RACES = JSON.parse(fs.readFileSync(path.join(SRC, 'races.json'), 'utf8'));
  const RULES = JSON.parse(fs.readFileSync(path.join(SRC, 'spells.json'), 'utf8'));
  const BUILDS = JSON.parse(fs.readFileSync(path.join(SRC, 'guides.json'), 'utf8')).builds;
  const maxPoints = g.client === 'tbc' ? 61 : 51;
  const credit = '-- GENERATED by tools/build_data.js for ' + g.title + '. Do not edit.\n' +
    '-- Talent trees, spell ranks, levels and icons: Blizzard client tables of build ' + BZ.build + ' (DB2 via wago.tools, datasrc/' + g.client + ').\n' +
    '-- Macro rules per spell and starter builds: WoWBoxer (macro rules seeded from the companion).\n' +
    '-- World of Warcraft names and icons (c) Blizzard Entertainment.\n';
  const files = {};
  const racials = {};
  for (const [k, r] of Object.entries(RACES.racials)) {
    racials[k] = { name: r.name, faction: r.faction, racials: r.racials.map(x => {
      const obj = { name: x.name, ranks: [{ r: 1, id: x.spellId }] };
      return Object.assign({ id: x.id, name: x.name, passive: !!x.passive, icon: BZ.racials[String(x.spellId)].f, spellId: x.spellId, only: x.only }, timing(obj));
    }) };
  }
  const common = {
    meta: { game: g.key, build: BZ.build, source: BZ.source, seed: D.meta.version },
    classOrder: D.classOrder, classes: D.classes, races: RACES.races, racials, core: RULES.core,
    engage: Object.assign({ id: K.ENGAGE.id, name: K.ENGAGE.name, level: K.ENGAGE.level, category: K.ENGAGE.category, action: K.ENGAGE.action, icon: K.ENGAGE.icon, gate: K.ENGAGE.gate, ranks: [] }, timing(K.ENGAGE)),
    roleSpec: K.ROLE_SPEC,
    reviewedNotIncluded: [],
  };
  files['Common.lua'] = credit + guard(g) + 'local D = ns.Data\n' +
    Object.entries(common).map(([k, v]) => 'D.' + k + ' = ' + toLua(v) + '\n').join('') +
    'D.talents, D.spells, D.guides = {}, {}, {}\n';
  const whTrees = {};
  const problems = [];
  for (const cls of D.classOrder) {
    const nodes = BZ.talents[cls];
    const keys = new Set(nodes.map(n => n.k));
    const nodeByName = {}; for (const n of nodes) nodeByName[n.n] = n;
    const talents = {
      trees: BZ.trees[cls].map(t => ({ n: t.n, f: t.f })),
      nodes: nodes.map(n => ({ k: n.k, n: n.n, t: n.t, r: n.r, c: n.c, m: n.m, f: n.f })),
      arrows: nodes.filter(n => n.req).map(n => [n.req, n.k]),
    };
    const book = BZ.spells[cls], icons = BZ.icons[cls];
    const seed = {}; for (const x of D.spells.filter(x => x.cls === cls)) seed[x.name] = x;
    const renames = (RULES.renames || {})[cls] || {};
    const fresh = (RULES.new || {})[cls] || {};
    const spells = [];
    const add = (name, base) => {
      const tb = book[name];
      if (!tb) { problems.push(cls + ': ' + name + ' is not a spell of this game'); return; }
      const o = spellOut(base);
      o.id = cls + '-' + name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
      if (base.name === name) o.id = base.id; // keep the seed's id (extras and overrides refer to it)
      o.name = name;
      o.ranks = tb.map(([id, l], i) => ({ r: i + 1, l: Math.max(1, l), id }));
      o.level = Math.max(1, tb[0][1]);
      o.forever = undefined; o.gateNote = undefined; o.disputed = undefined;
      if (typeof o.icon !== 'string' && icons[name]) o.icon = icons[name];
      const tn = nodeByName[name];
      if (tn) { o.gate = 'talent'; o.talent = tn.k; } else { o.gate = 'trainer'; o.talent = undefined; }
      spells.push(o);
    };
    for (const x of D.spells.filter(x => x.cls === cls)) if (book[x.name]) add(x.name, x);
    for (const [name, from] of Object.entries(renames)) if (seed[from]) add(name, seed[from]); else problems.push(cls + ': rename source ' + from + ' missing');
    for (const [name, r] of Object.entries(fresh)) {
      if (seed[name]) { problems.push(cls + ': ' + name + ' is already in the seed'); continue; }
      add(name, { id: '', name, category: r.category, action: r.action, icon: icons[name], form: r.form, lock: r.lock, ranks: [] });
    }
    // every name in the recommended macros must be a spell here
    const have = new Set(spells.map(x => x.name));
    for (const [role, items] of Object.entries(RULES.core[cls] || {})) for (const it of items) {
      const alts = Array.isArray(it) ? it : [it];
      for (const n of alts) if (!have.has(n)) problems.push(cls + '/' + role + ': core macro ' + n + ' is not a spell here');
    }
    // WoWBoxer starter builds, one per role (roles that share a build share the guide)
    const Tg = E.makeTree(talents);
    const guides = [];
    const seen = {};
    for (const role of D.classes[cls].roles) {
      const ranks = (BUILDS[cls] || {})[role];
      if (!ranks) { problems.push(cls + '/' + role + ': no starter build'); continue; }
      const sig = JSON.stringify(ranks);
      if (seen[sig]) continue;
      seen[sig] = true;
      const r = starterOrder(Tg, nodeByName, ranks, maxPoints, g.key + ' ' + cls + '/' + role, problems);
      const spec = talents.trees[r.main].n;
      guides.push({ id: 'wbx-' + g.key + '-' + cls + '-' + role, spec, label: spec + ' ' + r.split + ' – WoWBoxer starter build', kind: 'final-derived',
        default: guides.length === 0, note: 'WoWBoxer\'s starter build for ' + D.classes[cls].n + ' (' + role + '), all ' + maxPoints +
          ' points, main tree first. Compare it with a current ' + g.title + ' guide.',
        source: { site: 'WoWBoxer', title: 'Starter build', updated: '2026-11-02', scope: '10-' + (maxPoints + 9), purpose: role },
        order: r.order });
    }
    files['Class_' + cls + '.lua'] = credit + guard(g) + 'local D = ns.Data\n' +
      'D.talents.' + cls + ' = ' + toLua(talents) + '\n' +
      'D.spells.' + cls + ' = ' + toLua(spells) + '\n' +
      'D.guides.' + cls + ' = ' + toLua(guides) + '\n';
    // Wowhead's order: per tree, row then column (checked against Wowhead's calculator data, 2 Nov 2026)
    whTrees[cls] = [0, 1, 2].map(t => nodes.filter(n => n.t === t).sort((a, b) => a.r - b.r || a.c - b.c).map(n => ({ n: n.n, m: n.m })));
  }
  if (problems.length) throw new Error(g.title + ':\n  ' + problems.join('\n  '));
  const WH = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'vendor', 'wowhead', 'forever-trees.json'), 'utf8'));
  files['WowheadOrder.lua'] = '-- GENERATED by tools/build_data.js for ' + g.title + ': the talent order of Wowhead\'s calculator (row, then\n' +
    '-- column per tree, from the client tables), to read talent links. Names (c) Blizzard. Do not edit.\n' +
    guard(g) + 'ns.Data.wowhead = ' + toLua({ hashVersion: WH.hashVersion, tokens: WH.tokens, trees: whTrees }) + '\n';
  return files;
}

const check = process.argv.includes('--check');
let stale = 0, count = 0, bytes = 0;
for (const g of GAMES) {
  const OUT = path.join(DATA, g.dir);
  fs.mkdirSync(OUT, { recursive: true });
  for (const [f, txt] of Object.entries(g.client ? filesForClient(g) : filesFor(g))) {
    const p = path.join(OUT, f);
    count++; bytes += txt.length;
    if (check) { if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== txt) { console.error('stale: ' + g.dir + '/' + f); stale++; } }
    else fs.writeFileSync(p, txt);
  }
}
// nothing may be left directly in Data/ (the old single-game layout)
for (const f of fs.readdirSync(DATA)) if (/\.lua$/.test(f)) { console.error('left over: Data/' + f); stale++; }
if (stale) process.exit(1);
console.log((check ? 'checked ' : 'wrote ') + count + ' files, ' + bytes + ' bytes');
